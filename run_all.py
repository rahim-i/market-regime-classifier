"""Run the whole project from start to finish.

    python run_all.py            # use the saved data snapshot in data/raw/
    python run_all.py --refresh  # download fresh data first (results will change)
"""

import argparse
import time

import pandas as pd

from src import backtest, config, data, features, plots, prediction, regimes


def _fmt(v):
    if isinstance(v, float):
        return f"{v:,.0f}" if v.is_integer() else f"{v:,.2f}"
    return str(v)


def to_markdown(df: pd.DataFrame) -> str:
    """Small helper so we do not need the optional 'tabulate' package."""
    cols = [df.index.name or ""] + [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in df.iterrows():
        lines.append("| " + " | ".join([str(idx)] + [_fmt(v) for v in row]) + " |")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh", action="store_true", help="re-download market data")
    args = parser.parse_args()
    t0 = time.time()

    print("1/5  Loading data")
    daily = data.load_data(refresh=args.refresh)
    monthly = features.monthly_features(daily)
    print(f"     {len(daily):,} trading days -> {len(monthly)} complete months "
          f"({monthly.index[0]:%b %Y} to {monthly.index[-1]:%b %Y})")

    print("2/5  Detecting regimes (re-fitting the HMM every month; about a minute)")
    reg = regimes.filtered_regimes(monthly)
    summary = regimes.regime_summary(monthly, reg)

    print("3/5  Walk-forward predictions")
    dataset = prediction.build_dataset(monthly, reg)
    pred = prediction.run_predictions(dataset)

    print("4/5  Backtesting the regime-aware strategy")
    results, strat_table, cost_table = backtest.run_backtests(monthly, reg)

    print("5/5  Saving charts and tables")
    plots.plot_regimes(daily, reg)
    plots.plot_confusion(pred["regime_predictions"])
    plots.plot_equity(results)
    plots.plot_vol_forecast(pred["vol_predictions"])

    config.RESULTS_DIR.mkdir(exist_ok=True)
    reg.to_csv(config.RESULTS_DIR / "regimes.csv", float_format="%.4f")
    tables = {
        "Regime summary": summary,
        "Predicting next month's regime": pred["regime_metrics"],
        "Predicting next month's volatility": pred["vol_metrics"],
        "Strategy comparison": strat_table,
        "Sensitivity to trading costs (regime-aware strategy)": cost_table,
    }
    md = [f"# Results\n\nGenerated by `python run_all.py`. Regimes from "
          f"{reg.index[0]:%b %Y}; predictions from "
          f"{pred['regime_predictions'].index[0]:%b %Y}; data to {monthly.index[-1]:%b %Y}.\n"]
    for title, table in tables.items():
        slug = title.lower().split(" (")[0].replace(" ", "_").replace("'", "")
        table.to_csv(config.RESULTS_DIR / f"{slug}.csv")
        md.append(f"## {title}\n\n{to_markdown(table)}\n")
        print(f"\n{title}\n{table.to_string()}")
    (config.RESULTS_DIR / "results.md").write_text("\n".join(md))

    latest = reg.iloc[-1]
    print(f"\nLatest regime ({reg.index[-1]:%B %Y}): {latest['regime_name']} "
          f"(Calm {latest.p_calm:.0%}, Volatile {latest.p_volatile:.0%}, "
          f"Stress {latest.p_stress:.0%})")
    print(f"Done in {time.time() - t0:.0f}s. Charts in figures/, tables in results/.")


if __name__ == "__main__":
    main()
